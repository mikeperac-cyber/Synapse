import { NextResponse } from "next/server";
import { prisma } from "@/lib/prisma";
import JSZip from "jszip";

export const dynamic = "force-dynamic";

export async function GET() {
  try {
    const bundles = await prisma.repoBundle.findMany({
      orderBy: { createdAt: "desc" },
    });
    return NextResponse.json({ success: true, bundles });
  } catch (error: unknown) {
    console.error("GET bundler error:", error);
    return NextResponse.json({ success: false, error: "Failed to fetch bundles" }, { status: 500 });
  }
}

export async function POST(request: Request) {
  try {
    const body = await request.json();
    const {
      name = "OmniSphere Consolidated Monorepo",
      repoUrls = [],
      outputFormat = "ZIP", // "ZIP" | "XML_PROMPT" | "MARKDOWN"
      customFiles = [],
    } = body;

    const urls = Array.isArray(repoUrls) ? repoUrls : [repoUrls];

    // Standardized monorepo templates if simulating or bundling
    const filesToBundle: Array<{ path: string; content: string }> = [
      {
        path: "README.md",
        content: `# ${name}\n\nConsolidated multi-repo context pack generated by OmniSphere OS.\n\nSources:\n${urls.map((u: string) => `- ${u}`).join("\n")}\n\nGenerated: ${new Date().toISOString()}`,
      },
      {
        path: "package.json",
        content: JSON.stringify(
          {
            name: name.toLowerCase().replace(/[^a-z0-9]/g, "-"),
            version: "1.0.0",
            private: true,
            workspaces: ["packages/*", "apps/*"],
            scripts: {
              build: "turbo run build",
              dev: "turbo run dev",
              test: "turbo run test",
            },
          },
          null,
          2
        ),
      },
      {
        path: "packages/core/src/index.ts",
        content: `// OmniSphere Core Shared Engine\nexport const VERSION = "1.0.0";\nexport function initializeGateway() {\n  console.log("OmniSphere Core initialized.");\n}`,
      },
      {
        path: "packages/autonomous/src/daemon.ts",
        content: `// Autonomous Agent Reconciliation Loop\nexport async function runHeartbeat() {\n  return { status: "ACTIVE", uptime: process.uptime() };\n}`,
      },
      {
        path: "apps/web/src/manifest.json",
        content: JSON.stringify({ name: "OmniSphere OS Client", short_name: "OmniSphere" }, null, 2),
      },
    ];

    if (Array.isArray(customFiles)) {
      for (const cf of customFiles) {
        if (cf.path && cf.content) {
          filesToBundle.push(cf);
        }
      }
    }

    // Calculate metrics
    let totalContent = "";
    let totalBytes = 0;
    for (const f of filesToBundle) {
      totalContent += f.content + "\n";
      totalBytes += Buffer.byteLength(f.content, "utf8");
    }

    // Token estimation (~4 chars/token)
    const tokenEstimate = Math.round(totalContent.length / 4);

    // Build directory structure JSON
    const dirTree = {
      name: name,
      type: "directory",
      children: [
        {
          name: "packages",
          type: "directory",
          children: [
            { name: "core/src/index.ts", type: "file", size: "185 B" },
            { name: "autonomous/src/daemon.ts", type: "file", size: "210 B" },
          ],
        },
        {
          name: "apps",
          type: "directory",
          children: [{ name: "web/src/manifest.json", type: "file", size: "85 B" }],
        },
        { name: "package.json", type: "file", size: "320 B" },
        { name: "README.md", type: "file", size: "240 B" },
      ],
    };

    let xmlOutput = "";
    if (outputFormat === "XML_PROMPT") {
      xmlOutput = `<repository_context name="${name}" generated_at="${new Date().toISOString()}">\n`;
      xmlOutput += `  <metadata>\n    <token_estimate>${tokenEstimate}</token_estimate>\n    <file_count>${filesToBundle.length}</file_count>\n  </metadata>\n`;
      for (const f of filesToBundle) {
        xmlOutput += `  <file path="${f.path}">\n<![CDATA[\n${f.content}\n]]>\n  </file>\n`;
      }
      xmlOutput += `</repository_context>`;
    }

    // If zip format requested, construct in-memory zip
    let zipBase64 = "";
    if (outputFormat === "ZIP") {
      const zip = new JSZip();
      for (const f of filesToBundle) {
        zip.file(f.path, f.content);
      }
      zipBase64 = await zip.generateAsync({ type: "base64" });
    }

    const bundleRecord = await prisma.repoBundle.create({
      data: {
        name,
        repoUrlsJson: JSON.stringify(urls),
        directoryStructureJson: JSON.stringify(dirTree),
        fileCount: filesToBundle.length,
        totalSize: totalBytes,
        tokenEstimate,
        outputFormat,
      },
    });

    return NextResponse.json({
      success: true,
      bundle: bundleRecord,
      xmlPrompt: xmlOutput || undefined,
      zipBase64: zipBase64 || undefined,
      tokenEstimate,
      fileCount: filesToBundle.length,
    });
  } catch (error: unknown) {
    console.error("POST bundler error:", error);
    return NextResponse.json({ success: false, error: "Failed to bundle repository" }, { status: 500 });
  }
}
